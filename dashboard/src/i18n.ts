/**
 * Lightweight i18n for the admin console.
 *
 * Locale is a module-level Solid signal so every t() call re-renders on
 * switch; preference is persisted to localStorage. Default: zh.
 */

import { createSignal } from 'solid-js';

export type Locale = 'zh' | 'en';

const STORAGE_KEY = 'mygateway.locale';

function readStoredLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch { /* storage unavailable */ }
  return 'zh';
}

export const [locale, setLocale] = createSignal<Locale>(readStoredLocale());

export function switchLocale(next: Locale): void {
  setLocale(next);
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* storage unavailable */ }
}

export function toggleLocale(): void {
  switchLocale(locale() === 'zh' ? 'en' : 'zh');
}

